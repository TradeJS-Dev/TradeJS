type GridClassicRuntimeDefaults = {
  -readonly [Key in keyof typeof config]: WidenConfigLiteral<
    (typeof config)[Key]
  >;
};

export type GridClassicConfig = StrategyConfig &
  Omit<
    GridClassicRuntimeDefaults,
    | 'BACKTEST_PRICE_MODE'
    | 'GRIDCLASSIC_MODE'
    | 'GRIDCLASSIC_ENTRY_CONFIRMATION'
    | 'GRIDCLASSIC_TP_MODE'
    | 'LONG'
    | 'SHORT'
  > & {
    BACKTEST_PRICE_MODE: BacktestPriceMode;
    GRIDCLASSIC_MODE: GridClassicMode;
    GRIDCLASSIC_ENTRY_CONFIRMATION: GridClassicEntryConfirmation;
    GRIDCLASSIC_TP_MODE: GridClassicTakeProfitMode;
    LONG: GridClassicSideConfig;
    SHORT: GridClassicSideConfig;
  };
